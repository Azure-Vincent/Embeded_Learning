// Generates src/blobs.h for fw_updater.c: a P-256 public key and a zlib-compressed text block.
// Deterministic. The key pair is derived from a published string, so it protects nothing: it is a teaching prop.
import { createECDH, createHash } from 'node:crypto';
import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';

const ecdh = createECDH('prime256v1');
ecdh.setPrivateKey(createHash('sha256').update('bench-fwimages synthetic vendor key, not a secret').digest());
const pub = ecdh.getPublicKey(); // 65 bytes, 0x04 || X || Y

// Deterministic pseudo-text so the compressed block has a useful size.
let seed = 0x1234abcd;
const rnd = () => { seed ^= seed << 13; seed >>>= 0; seed ^= seed >>> 17; seed ^= seed << 5; seed >>>= 0; return seed; };
const words = ('recovery console flash erase verify image slot sector boot fail retry ok error uart baud clock key ' +
  'signature hash write read page offset length version update rollback counter watchdog reset status').split(' ');
let text = '';
for (let line = 0; line < 420; line++) {
  const n = 3 + (rnd() % 6);
  const parts = [];
  for (let i = 0; i < n; i++) parts.push(rnd() % 5 === 0 ? '0x' + (rnd() >>> 12).toString(16) : words[rnd() % words.length]);
  text += `[${String(line).padStart(4, '0')}] ${parts.join(' ')}\r\n`;
}
const z = deflateSync(Buffer.from(text, 'latin1'), { level: 9 });
const arr = (b) => '{' + [...b].map((x) => '0x' + x.toString(16).padStart(2, '0')).join(',') + '}';
writeFileSync(new URL('./src/blobs.h', import.meta.url),
  `/* Generated by tools/fwimages/gen_blobs.mjs. Do not edit. */\n#ifndef BLOBS_H\n#define BLOBS_H\n` +
  `/* P-256 public key, SEC1 uncompressed, ${pub.length} bytes */\n#define VENDOR_PUBKEY_BYTES ${arr(pub)}\n` +
  `/* zlib stream, ${z.length} bytes, inflates to ${text.length} bytes of text */\n#define RECOVERY_ZLIB_BYTES ${arr(z)}\n#endif\n`);
console.log(`blobs.h: pubkey ${pub.length} B, zlib ${z.length} B (from ${text.length} B)`);
