#!/usr/bin/env node
// Turn build/manifest.json + build/results.tsv into RESULTS.md (written to stdout).
// Called by build-all.sh after a full run; not meant to be run by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(HERE, 'build', 'manifest.json'), 'utf8'));
const results = new Map(fs.readFileSync(path.join(HERE, 'build', 'results.tsv'), 'utf8').split('\n').filter(Boolean)
  .map((l) => { const [id, status, secs, warn, ...err] = l.split('\t'); return [id, { status, secs, warn: +warn, err: err.join(' ') }]; }));
const env = process.env;
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const built = manifest.filter((m) => !m.skip);
const pass = built.filter((m) => results.get(m.id)?.status === 'PASS');
const fail = built.filter((m) => results.get(m.id)?.status !== 'PASS');
const skipped = manifest.filter((m) => m.skip);
const where = (m) => `${m.section} / ${m.unitKind} \`${m.unit}\` \`${m.path}\``;

const out = [];
out.push('# ESP-IDF build results', '');
out.push('Generated by `tools/idf-check/build-all.sh`. Do not edit by hand; rerun the script.', '');
out.push(`- Date: ${new Date().toISOString().slice(0, 10)}`);
out.push(`- ESP-IDF: ${env.IDF_VER_FILE || '?'} (\`git describe\`: ${env.IDF_VER || '?'}), target \`${env.TARGET || 'esp32'}\`, xtensa-esp32-elf-gcc ${env.GCC_VER || '?'}`);
out.push(`- Listings that define \`app_main\`: ${manifest.length}`);
out.push(`- Built: ${built.length} — **${pass.length} pass, ${fail.length} fail**`);
out.push(`- Not built: ${skipped.length} (${skipped.filter((m) => m.sameAs).length} identical copies of a built listing, ${skipped.filter((m) => !m.sameAs).length} fragments)`, '');
out.push('"Pass" means `idf.py build` configured, compiled and linked an app image for the target. Nothing was flashed or run.',
  'The id is `<lesson or lab id>-<n>`, where n counts the code listings of that lesson or lab in document order (see README.md).', '');

if (fail.length) {
  out.push('## Failures', '');
  for (const m of fail) {
    const r = results.get(m.id) || { err: 'not built' };
    out.push(`### ${m.id}`, '', `- Where: ${where(m)}${m.caption ? ` — "${esc(m.caption)}"` : ''}`,
      `- Declared status: \`${m.status || 'none'}\`; main/CMakeLists.txt: ${m.cmakeMain}; top-level: ${m.cmakeTop}`,
      '- First error:', '', '```', r.err || '(none recorded)', '```', '', `Full log: \`tools/idf-check/build/${m.id}/build.log\` (after running the build locally).`, '');
  }
}

out.push('## All programs', '');
out.push('| id | result | declared status | block | lines | main/CMakeLists.txt | warnings in main/ | first error |', '|---|---|---|---|---|---|---|---|');
for (const m of manifest) {
  const r = results.get(m.id);
  const result = m.skip ? (m.sameAs ? `same as ${m.sameAs}` : 'not built') : (r ? r.status : 'not run');
  const cm = m.skip ? '' : m.cmakeMain === 'generated' ? `generated; PRIV_REQUIRES ${m.inferredRequires.join(' ') || '(none)'}` : m.cmakeMain;
  out.push(`| ${m.id} | ${result} | ${m.status || '-'} | ${m.blockKind} | ${m.lines} | ${esc(cm)} | ${m.skip ? '' : r?.warn ?? ''} | ${esc(m.skip && !m.sameAs ? m.skip : r?.err ? '`' + r.err.replace(/`/g, "'") + '`' : '')} |`);
}
out.push('', '## Where each id lives', '', '| id | location | caption |', '|---|---|---|');
for (const m of manifest) out.push(`| ${m.id} | ${where(m)}${m.joinedFrom ? ` (joined with listings ${m.joinedFrom.join(', ')} before it)` : ''} | ${esc(m.caption).slice(0, 140)} |`);
out.push('');
const extra = built.filter((m) => m.extraFiles || m.sourceFiles);
if (extra.length) {
  out.push('## Extra files taken from the same lab', '');
  for (const m of extra) out.push(`- ${m.id}: ${[...(m.sourceFiles || []), ...(m.extraFiles || [])].join(', ')}`);
  out.push('');
}
process.stdout.write(out.join('\n'));
